"""Interactive portfolio research dashboard. Run: streamlit run dashboard.py"""
from pathlib import Path
import json
import pandas as pd
import plotly.express as px
import plotly.graph_objects as go
import streamlit as st

BASE = Path(__file__).resolve().parent
st.set_page_config(page_title="Portfolio Research Lab", page_icon="📊", layout="wide")
st.title("Investment Data & Portfolio Research")
st.warning("**SYNTHETIC DEMONSTRATION.** Prices and research results were generated by simulation; they are not actual market observations or investment advice")
if not (BASE/'outputs/results.json').exists():
    st.error("Run `python -m src.run_pipeline` first")
    st.stop()
report=json.loads((BASE/'outputs/results.json').read_text())
df=pd.read_csv(BASE/'outputs/daily_backtest.csv',parse_dates=['date']).set_index('date')
w=pd.read_csv(BASE/'outputs/portfolio_weights.csv',parse_dates=['date']).set_index('date')
st.sidebar.header("Research controls")
period=st.sidebar.selectbox("Evaluation period",["Out of sample (2023–2025)","Development (2021–2022)","Full evaluation (2021–2025)"])
start,end= {"Out of sample (2023–2025)":('2023-01-02','2025-12-31'),"Development (2021–2022)":('2021-01-01','2022-12-30'),"Full evaluation (2021–2025)":('2021-01-01','2025-12-31')}[period]
fee=st.sidebar.slider("Transaction cost (bps per unit turnover)",0,50,10,5)
sub=df.loc[start:end].copy()
sub['strategy_after_costs']=sub.strategy_gross - sub.turnover*fee/10000
from src.backtest import metrics
m=metrics(sub.strategy_after_costs); bench=metrics(sub.benchmark)
a,b,c,d=st.columns(4)
a.metric('Strategy CAGR',f'{m["cagr_pct"]:.2f}%')
b.metric('Reference CAGR',f'{bench["cagr_pct"]:.2f}%')
c.metric('Sharpe · 0% risk-free',m['sharpe_0rf'])
d.metric('Max drawdown',f'{m["max_drawdown_pct"]:.2f}%')
wealth=(1+sub[['strategy_after_costs','benchmark']]).cumprod()*10000
fig=go.Figure()
for col,label in [('strategy_after_costs','Strategy (net)'),('benchmark','Equal-weight reference')]:
    fig.add_trace(go.Scatter(x=wealth.index,y=wealth[col],name=label,mode='lines'))
fig.update_layout(title='Growth of $10,000 · selected evaluation period',yaxis_title='Simulated portfolio value',hovermode='x unified',height=420)
st.plotly_chart(fig,use_container_width=True)
l,r=st.columns(2)
with l:
    dd=(wealth/wealth.cummax()-1)*100
    st.plotly_chart(px.line(dd,title='Drawdown (%)'),use_container_width=True)
with r:
    # Only rebalance dates are meaningful for the recorded model allocations.
    st.plotly_chart(px.area(w.loc[start:end].resample('MS').first().fillna(0),title='Portfolio weights by month'),use_container_width=True)
st.subheader('Risk, robustness & data quality')
a,b=st.columns(2)
with a:
    st.write('**Synthetic-market holdout: transaction-cost sensitivity**')
    st.dataframe(pd.DataFrame({k:v for k,v in report['cost_sensitivity'].items()}).T[['cagr_pct','sharpe_0rf','max_drawdown_pct']].rename(columns={'cagr_pct':'CAGR %','sharpe_0rf':'Sharpe','max_drawdown_pct':'Max DD %'}),use_container_width=True)
with b:
    st.write('**Ingestion / validation checks**')
    st.dataframe(pd.DataFrame({'Check':list(report['validation']),'Passed':list(report['validation'].values())}),hide_index=True,use_container_width=True)
st.write('**Exploratory block-bootstrap confidence interval (CAGR spread, percentage points):**',report['uncertainty']['ci_95_pp'])
st.caption('Signals are lagged two sessions to allow previous-close execution; positions rebalanced monthly. Holdout fixed before inspection. Benchmark has no transaction costs. Simulation omits market impact, borrow constraints, taxes and real broker execution. See docs/METHODOLOGY.md.')
with st.expander('See daily audit data'):
    st.dataframe(sub.tail(100).sort_index(ascending=False),use_container_width=True)
